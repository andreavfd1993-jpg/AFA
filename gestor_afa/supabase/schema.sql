create extension if not exists pgcrypto;

create table if not exists public.afa_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  id uuid primary key default gen_random_uuid(),
  member_number bigint generated by default as identity unique,
  full_name text not null,
  email text not null,
  phone text,
  course text,
  dni text,
  address text,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists members_email_lower_unique on public.members (lower(email));

create or replace function public.is_afa_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.afa_admins
    where user_id = auth.uid()
  );
$$;

alter table public.afa_admins enable row level security;
alter table public.members enable row level security;

drop policy if exists "Admins can read members" on public.members;
create policy "Admins can read members" on public.members
for select to authenticated using (public.is_afa_admin());

drop policy if exists "Admins can insert members" on public.members;
create policy "Admins can insert members" on public.members
for insert to authenticated with check (public.is_afa_admin());

drop policy if exists "Admins can update members" on public.members;
create policy "Admins can update members" on public.members
for update to authenticated using (public.is_afa_admin()) with check (public.is_afa_admin());

-- No se habilita borrado físico desde la aplicación: se recomienda marcar como "Baja".
-- No se crea ninguna política pública para leer o modificar datos.

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists members_updated_at on public.members;
create trigger members_updated_at before update on public.members
for each row execute function public.set_updated_at();

